"""Freeze M1/M2 and reproduce EXACT prior QQ training and test RNG streams.
No estimated predictions are generated by this module. True risks unchanged.
"""
from pathlib import Path
import hashlib, json, sys
import numpy as np
ROOT=Path(__file__).resolve().parent
OUT=ROOT/"data";OUT.mkdir(parents=True,exist_ok=True)
N_TRAIN=2000;N_TEST=2000;R=int(sys.argv[1]) if len(sys.argv)>1 else 2

def hazards(z,m):
    z1,z2=z.T
    b1=.18*np.exp(.15*z1+.15*z2)
    b2=.15*np.exp(-.10*z1+.20*z2)
    n=len(z);h=np.empty((n,2,2,2),dtype=float)
    h[:,0,0,:]=b1[:,None];h[:,0,1,:]=b2[:,None]
    if m=="M1":
        t1=np.exp(np.log(.6)+.65*z1);t2=np.exp(np.log(2.)+.25*(2*z2-1))
        h[:,0,0,0]*=2.;h[:,0,0,1]*=.5
        h[:,0,1,0]*=.5;h[:,0,1,1]*=2.
        h[:,1,0,:]=h[:,0,0,:]*t1[:,None]
        h[:,1,1,:]=h[:,0,1,:]*t2[:,None]
    elif m=="M2":
        h[:,1,0,0]=b1*np.exp(np.log(.5)+.35*z1)
        h[:,1,0,1]=b1*np.exp(np.log(2.5)+.35*z1)
        h[:,1,1,:]=b2[:,None]*np.exp(np.log(.7)+.25*(2*z2-1))[:,None]
    else:raise ValueError(m)
    return h

def make_sample(rng,m,n):
    z=np.column_stack([rng.uniform(-1,1,n),rng.binomial(1,.5,n)])
    a=rng.binomial(1,.5,n)
    rate=hazards(z,m)[np.arange(n),a]
    total=rate.sum(axis=1);E=rng.exponential(1.,n)
    h0=total[:,0];h1=total[:,1];early=E<=h0
    t=np.where(early,E/h0,1+(E-h0)/h1)
    segment=np.where(early,0,1)
    p1=rate[np.arange(n),0,segment]/total[np.arange(n),segment]
    j=np.where(rng.random(n)<p1,1,2)
    cens=rng.exponential(1/.08,n)
    x=np.minimum(t,cens);status=np.where(t<=cens,j,0)
    return z,a,x,status

streams=np.random.SeedSequence(42).spawn(20)
entries=[]
for rep in range(R):
    rg=np.random.default_rng(streams[rep])
    ztest=np.column_stack([rg.uniform(-1,1,N_TEST),rg.binomial(1,.5,N_TEST)])
    tie_coin=rg.binomial(1,.5,N_TEST)
    for mi,m in enumerate(("M1","M2")):
        rng=np.random.default_rng(np.random.SeedSequence([2026112407,rep,mi]))
        z,a,x,status=make_sample(rng,m,N_TRAIN)
        raw=np.column_stack([z,a,x,status])
        train=np.column_stack([z,a,x,status,(status>0).astype(int),(status==1).astype(int),(status==2).astype(int),np.full(N_TRAIN,.5)])
        test=np.column_stack([np.arange(N_TEST),ztest,tie_coin])
        tpath=OUT/f"train_{m}_r{rep+1}.csv";vpath=OUT/f"test_{m}_r{rep+1}.csv"
        np.savetxt(tpath,train,delimiter=",",header="Z1,Z2,Trt,obs_time,status,D.0,D.1,D.2,piz",comments="",fmt="%.17g")
        np.savetxt(vpath,test,delimiter=",",header="id,Z1,Z2,tie_coin",comments="",fmt="%.17g")
        entries.append(dict(mechanism=m,rep=rep+1,train_binary_sha256=hashlib.sha256(raw.tobytes()).hexdigest(),train_csv_sha256=hashlib.sha256(tpath.read_bytes()).hexdigest(),test_csv_sha256=hashlib.sha256(vpath.read_bytes()).hexdigest(),realized_censor_pct=float(100*np.mean(status==0))))
(OUT/"manifest.json").write_text(json.dumps(dict(n_train=N_TRAIN,n_test=N_TEST,reps=R,train_seed=2026112407,test_seed=42,exponential_censor_rate=.08,thresholds=dict(p_all=.50,p1=.10,L=3.,delta=.25),entries=entries),indent=2),encoding="utf8")
print("Generated",len(entries),"paired datasets, ntrain",N_TRAIN,"ntest",N_TEST)
